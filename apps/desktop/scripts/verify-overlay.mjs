/**
 * Prove that every change this product layers onto someone else's bytes still applies.
 *
 * Harness-CN is not a fork that owns its sources: the client, most plugins and the runtime are
 * published packages, and this product changes a handful of their *built* files at package time —
 * a QQ console entry point, a null-guarded model selector, a class table, two rewritten WeChat
 * modules, an empty state, and a plugin list. Each of those edits anchors on a string that the
 * vendor may rewrite in any release.
 *
 * There are only two ways such an edit can fail, and both are silent:
 *   - the script throws while the seed is being built (loud enough: the build stops), or
 *   - the script finds no anchor and skips (quiet: the build succeeds, the feature is gone).
 *
 * This script runs the quiet case as a visible one. It asks every `patch-*.mjs` in this directory
 * for its state against a real installed tree, checks the class names our injected stylesheet
 * selects on, and exits non-zero when a patch can no longer be applied. Run it after every runtime
 * install and before every release:
 *
 *   node apps/desktop/scripts/verify-overlay.mjs [--tree <profile>] [--seed <seed dir>]
 *
 * `--tree` defaults to the desktop profile of the installed app (or `$HARNESS_CN_PROFILE`); the
 * seed check is skipped unless `--seed` points at a seed directory, because the seed only exists on
 * a packaging machine.
 */

import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Patches that edit an installed profile's `node_modules`, with the argument each expects. */
const TREE_PATCHES = [
  { script: 'patch-qqbot-console.mjs', target: 'node_modules' },
  { script: 'patch-workbuddy-model-null.mjs', target: 'node_modules' },
  { script: 'patch-wechat-identity.mjs', target: 'node_modules' },
  { script: 'patch-wechat-sessions.mjs', target: 'node_modules' },
  { script: 'patch-remote-ssh-empty-state.mjs', target: 'node_modules' },
  { script: 'patch-rule-engine.mjs', target: 'node_modules' },
]

/** Patches that edit a seed directory (only present while packaging). */
const SEED_PATCHES = [{ script: 'patch-seed-plugins.mjs', target: 'seed' }]

/** Bundles that carry the class names the injected stylesheet selects on. */
const STYLE_BUNDLES = [
  join('@deepseek-ai', 'dsh-client-ui-conversation', 'lib', 'client.js'),
  join('@deepseek-ai', 'dsh-client-ui-workspace', 'lib', 'client.js'),
]

/** The stylesheet this product injects into every window. */
const OVERRIDES = join(HERE, '..', '..', 'desktop-shell', 'rsc', 'plugin-overrides.css')

/** A CSS-module class name: `file_Hash` pairs are generated by the bundler, so they are the
 * selectors that can move when the vendor rebuilds. */
const MODULE_CLASS = /\.([A-Za-z][A-Za-z0-9]*_[A-Za-z0-9]+)/gu

/**
 * Split argv into the paths this script needs.
 * @returns the profile tree and seed directory, each possibly undefined.
 */
function parseArgs() {
  const argv = process.argv.slice(2)
  const valueOf = (flag) => {
    const index = argv.indexOf(flag)
    return index === -1 ? undefined : argv[index + 1]
  }
  const profile = valueOf('--tree')
    ?? process.env.HARNESS_CN_PROFILE
    ?? join(process.env.HARNESS_CN_INSTALL ?? 'D:\\Harness\\Harness-CN', 'data', 'profiles', 'desktop')
  return { profile, seed: valueOf('--seed') }
}

/**
 * Run one patch script in `--check` mode and read its JSON line.
 * @param script - file name in this directory.
 * @param root - argument the script inspects.
 * @returns the parsed result, or a synthetic `error` state carrying the child's stderr.
 */
function checkPatch(script, root) {
  const result = spawnSync(process.execPath, [join(HERE, script), '--check', root], {
    encoding: 'utf8',
    timeout: 120_000,
  })
  const line = (result.stdout ?? '').trim().split(/\r?\n/u).filter((entry) => entry.startsWith('{')).at(-1)
  if (line === undefined) {
    const detail = (result.stderr ?? '').trim().split(/\r?\n/u).at(-1) ?? `exit ${String(result.status)}`
    return { patch: script.replace(/^patch-|\.mjs$/gu, ''), state: 'error', detail }
  }
  return JSON.parse(line)
}

/**
 * Collect the CSS-module classes the injected stylesheet depends on.
 * @returns unique class names.
 */
function overrideClasses() {
  if (!existsSync(OVERRIDES)) return []
  const text = readFileSync(OVERRIDES, 'utf8')
  return [...new Set([...text.matchAll(MODULE_CLASS)].map((match) => match[1]))]
}

/**
 * Check that each class name still exists in a bundle that ships it.
 *
 * A tree with none of the bundles (a fixture, a seed without the client packages) reports every
 * class as `absent` rather than missing: "the package is not here" is not "the selector moved".
 * @param nodeModules - the profile's `node_modules`.
 * @param classes - names to look for.
 * @returns one entry per class.
 */
function checkClasses(nodeModules, classes) {
  const files = STYLE_BUNDLES.map((relative) => join(nodeModules, relative)).filter((file) => existsSync(file))
  if (files.length === 0) return classes.map((name) => ({ patch: `css:${name}`, state: 'absent' }))
  const bodies = files.map((file) => readFileSync(file, 'utf8'))
  return classes.map((name) => ({
    patch: `css:${name}`,
    state: bodies.some((body) => body.includes(name)) ? 'present' : 'missing',
  }))
}

const NAMES = {
  absent: 'not installed',
  patched: 'applied',
  pristine: 'anchor ok, applies',
  drifted: 'ANCHOR GONE',
  present: 'present',
  missing: 'MISSING',
  error: 'ERROR',
}

/**
 * Print the table and return whether anything failed.
 * @param rows - check results in display order.
 * @returns true when every row is healthy.
 */
function print(rows) {
  const width = Math.max(...rows.map((row) => row.patch.length))
  for (const row of rows) {
    const name = NAMES[row.state] ?? row.state
    process.stdout.write(`  ${row.patch.padEnd(width)}  ${name}${row.detail === undefined ? '' : `  (${row.detail})`}\n`)
  }
  const failed = rows.filter((row) => row.state === 'drifted' || row.state === 'missing' || row.state === 'error')
  const applied = rows.filter((row) => row.state === 'patched' || row.state === 'present').length
  const pending = rows.filter((row) => row.state === 'pristine').length
  const skipped = rows.filter((row) => row.state === 'absent').length
  process.stdout.write(`\n${String(rows.length)} checks: ${String(applied)} applied, ${String(pending)} pending, ${String(skipped)} not installed, ${String(failed.length)} broken\n`)
  return failed.length === 0
}

const { profile, seed } = parseArgs()
if (!existsSync(profile)) {
  process.stderr.write(`verify-overlay: no profile at ${profile}\n  pass --tree <profile directory> or set HARNESS_CN_PROFILE\n`)
  process.exit(2)
}
const nodeModules = existsSync(join(profile, 'node_modules')) ? join(profile, 'node_modules') : profile
process.stdout.write(`verify-overlay: ${resolve(nodeModules)}\n`)

const rows = []
for (const patch of TREE_PATCHES) rows.push(checkPatch(patch.script, patch.target === 'node_modules' ? nodeModules : profile))
if (seed !== undefined) {
  for (const patch of SEED_PATCHES) rows.push(checkPatch(patch.script, seed))
} else {
  rows.push({ patch: 'seed-plugins', state: 'absent', detail: 'no --seed given' })
}
rows.push(...checkClasses(nodeModules, overrideClasses()))

process.exit(print(rows) ? 0 : 1)
